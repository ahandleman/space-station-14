namespace Content.Client.Guidebook.Controls;

/// <summary>
/// Displays a mature plant, its harvest products, and their extraction outputs from prototype data.
/// </summary>
[UsedImplicitly, GenerateTypedNameReferences]
public sealed partial class GuidePlantEmbed : PanelContainer, IDocumentTag, ISearchableControl, IPrototypeRepresentationControl
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IComponentFactory _factory = default!;
    [Dependency] private IEntitySystemManager _systems = default!;
    [Dependency] private ILogManager _logs = default!;

    public IPrototype? RepresentedPrototype { get; private set; }

    public GuidePlantEmbed()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public GuidePlantEmbed(EntityPrototype plant) : this()
    {
        GenerateControl(plant);
    }

    public bool TryParseTag(Dictionary<string, string> args, [NotNullWhen(true)] out Control? control)
    {
        control = null;
        if (!args.TryGetValue("Plant", out var id)
            || !_prototype.TryIndex<EntityPrototype>(id, out var plant)
            || plant.Abstract
            || !plant.HasComp<PlantDataComponent>(_factory)
            || !plant.HasComp<PlantComponent>(_factory))
        {
            _logs.GetSawmill("guidebook.plant").Error("Plant embed requires a valid plant entity prototype in its Plant argument.");
            return false;
        }

        GenerateControl(plant);
        control = this;
        return true;
    }

    public bool CheckMatchesSearch(string query) => this.ChildrenContainText(query);

    public void SetHiddenState(bool state, string query)
    {
        Visible = CheckMatchesSearch(query) ? state : !state;
    }

    private void GenerateControl(EntityPrototype plant)
    {
        if (!plant.TryComp<PlantDataComponent>(out var data, _factory)
            || !plant.TryComp<PlantComponent>(out var growth, _factory))
            return;

        RepresentedPrototype = plant;
        var icon = new GuideEntityEmbed(plant.ID, false, false) { Scale = new Vector2(2, 2) };
        IconContainer.AddChild(icon);

        // Plant visuals normally start hidden or in their first growth stage.
        // Show the same harvest-ready layer used by PlantVisualizerSystem.
        if (icon.Sprite is { } sprite)
        {
            var sprites = _systems.GetEntitySystem<SpriteSystem>();
            sprites.LayerSetVisible(sprite.AsNullable(), PlantLayers.Plant, true);
            sprites.LayerSetRsiState(sprite.AsNullable(), PlantLayers.Plant, "harvest");
        }

        PlantName.SetMessage(Message(Loc.GetString(data.Name), true));

        foreach (var productId in data.ProductPrototypes.Distinct())
        {
            var product = _prototype.Index(productId);
            var productInfo = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Vertical,
                HorizontalExpand = true,
            };
            productInfo.AddChild(new GuideEntityEmbed(product.ID, false, false) { Scale = new Vector2(2, 2) });
            productInfo.AddChild(Text(product.Name, true));
            ProduceGrid.AddChild(productInfo);

            Solution? grind = null;
            Solution? juice = null;
            if (product.TryComp<ExtractableComponent>(out var extractable, _factory))
            {
                juice = extractable.JuiceSolution;
                if (extractable.GrindableSolutionName is { } solutionName)
                {
                    var targetSolution = product.TryComp<ProduceComponent>(out var produce, _factory)
                        ? produce.TargetSolution
                        : "food"; // Harvesting ensures ProduceComponent even on non-food products.

                    if (solutionName == targetSolution
                        && plant.TryComp<PlantChemicalsComponent>(out var chemicals, _factory))
                    {
                        // Harvesting replaces this solution with the plant's chemicals.
                        grind = new Solution();
                        foreach (var (reagent, quantity) in chemicals.Chemicals)
                            grind.AddReagent(reagent, quantity.GetQuantity(growth.Potency));
                    }
                    else
                    {
                        _systems.GetEntitySystem<SharedSolutionContainerSystem>()
                            .TryGetSolution(product, solutionName, out grind);
                    }
                }
            }

            ProduceGrid.AddChild(SolutionList(grind));
            ProduceGrid.AddChild(SolutionList(juice));
        }

        MutationsContainer.Visible = data.MutationPrototypes.Count > 0;
        foreach (var targetId in data.MutationPrototypes.Distinct())
        {
            var target = _prototype.Index(targetId);
            var name = target.TryComp<PlantDataComponent>(out var targetData, _factory)
                ? Loc.GetString(targetData.Name)
                : target.Name;
            var link = new GuidebookRichPrototypeLink
            {
                LinkedPrototype = target,
                HorizontalExpand = true,
            };
            link.SetMessage(Message(name));
            MutationLinks.AddChild(link);
        }
    }

    private BoxContainer SolutionList(Solution? solution)
    {
        var list = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        if (solution == null || solution.Contents.Count == 0)
        {
            list.AddChild(Text(Loc.GetString("guidebook-plant-no-extraction")));
            return list;
        }

        foreach (var entry in solution.Contents.OrderBy(r => _prototype.Index(r.Reagent.Prototype).LocalizedName))
        {
            list.AddChild(new GuideReagentLink(_prototype.Index(entry.Reagent.Prototype)));
        }

        return list;
    }

    private static RichTextLabel Text(string text, bool bold = false)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMessage(Message(text, bold));
        return label;
    }

    private static FormattedMessage Message(string text, bool bold = false)
    {
        var message = new FormattedMessage();
        if (bold)
            message.PushTag(new MarkupNode("bold", null, null));
        message.AddText(text);
        if (bold)
            message.Pop();
        return message;
    }
}
