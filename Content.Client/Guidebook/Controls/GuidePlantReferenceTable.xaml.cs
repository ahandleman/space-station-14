using System.Globalization;
using System.Text.RegularExpressions;
using Content.Client.Message;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Guidebook.Controls;

/// <summary>
/// Shared layout and formatting for the prototype-driven botany reference tables.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class GuidePlantReferenceTable : PanelContainer
{
    public GuidePlantReferenceTable(string title, string note, params string[] headings)
    {
        RobustXamlLoader.Load(this);
        TableTitle.SetMarkup($"[bold]{FormattedMessage.EscapeText(title)}[/bold]");
        TableNote.SetMarkup(note);
        Rows.Columns = headings.Length;
        foreach (var heading in headings)
            Rows.AddChild(Text($"[bold]{FormattedMessage.EscapeText(heading)}[/bold]"));
    }

    public void AddCell(Robust.Client.UserInterface.Control cell) => Rows.AddChild(cell);

    public static RichTextLabel Text(string markup)
    {
        var label = new RichTextLabel { HorizontalExpand = true };
        label.SetMarkup(markup);
        return label;
    }

    public static string Name(string id)
    {
        return Loc.TryGetString($"guidebook-plant-table-{id.ToLowerInvariant()}", out var name)
            ? name
            : Regex.Replace(id, "([a-z])([A-Z])", "$1 $2");
    }

    public static string Percent(float value) => (value * 100f).ToString("0.###", CultureInfo.CurrentCulture) + "%";
}
