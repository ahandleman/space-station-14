// Pure recursive authoring operations; GUI/API integration is checked separately.
import assert from 'node:assert/strict';
import {clone,roomPaths,locate,renameItem,reparentRoom,duplicateRoom,removeItem,programStats,measurementKey} from '../wwwroot/authoring.js';
import {definitionAt,treeHtml} from '../wwwroot/design-renderer.js';
const room=(id,children=[])=>({id,name:id,role:'activity',tags:[],count:{min:1,target:1,max:3},area:{min:2,target:4,max:12},connections:[],access:{entryOwners:[]},rooms:children});
const booth=room('Booth',[room('Cabinet')]),chapel=room('Chapel',[booth,room('Store')]);chapel.count.min=2;
booth.connections=[{id:'Parent',from:'',to:['..']},{id:'Sibling',from:'',to:['../Store']},{id:'Child',from:'',to:['./Cabinet']}];
const source={departments:[{id:'Service',name:'Service',rooms:[chapel,room('Library')]},{id:'Commons',name:'Commons',rooms:[room('Lounge')]}],maintenance:{rooms:[]},connections:[{id:'NestedTarget',from:'Commons/Lounge',to:['Service/Chapel/Booth/Cabinet']}],choices:[{rooms:['Service/Chapel/Booth']}]};
assert.equal(roomPaths(source).length,6);
assert.equal(locate(source,'Service/Chapel/Booth').parentPath,'Service/Chapel');
assert.equal(definitionAt(source,'Service/Chapel/Booth/Cabinet').id,'Cabinet');
assert.equal(measurementKey({path:'Service/Chapel/Booth/Cabinet',instanceId:'1',parentInstanceId:'Service/Chapel#2/Booth#1'}),'Service/Chapel#2/Booth#1/Cabinet#1');
assert.equal(programStats(source).required,10,'Child minimum counts multiply by actual ancestor minima.');
assert.equal(renameItem(source,'Service/Chapel/Store','Closet'),'Service/Chapel/Closet');
assert.deepEqual(booth.connections[1].to,['Service/Chapel/Closet']);
assert.equal(renameItem(source,'Service/Chapel','Sanctuary'),'Service/Sanctuary');
assert.deepEqual(source.connections[0].to,['Service/Sanctuary/Booth/Cabinet']);
assert.deepEqual(source.choices[0].rooms,['Service/Sanctuary/Booth']);
assert.deepEqual(booth.connections[0].to,['Service/Sanctuary']);
const moved=reparentRoom(source,'Service/Sanctuary/Booth','Commons/Lounge');
assert.equal(moved,'Commons/Lounge/Booth');
assert.equal(locate(source,moved).item,booth);
assert.deepEqual(booth.connections[0].to,['Service/Sanctuary'],'Moving a room must not silently retarget its authored parent dependency.');
assert.deepEqual(booth.connections[2].to,['Commons/Lounge/Booth/Cabinet']);
assert.deepEqual(source.connections[0].to,['Commons/Lounge/Booth/Cabinet']);
assert.throws(()=>reparentRoom(source,'Commons/Lounge','Commons/Lounge/Booth'));
const copyPath=duplicateRoom(source,moved);
assert.equal(copyPath,'Commons/Lounge/BoothCopy');
assert.deepEqual(locate(source,copyPath).item.connections[2].to,['Commons/Lounge/BoothCopy/Cabinet']);
assert.equal(removeItem(source,moved),true);
assert.equal(locate(source,moved),null);
assert.deepEqual(source.connections[0].to,['Commons/Lounge/Booth/Cabinet'],'Removing a subtree keeps broken external dependencies reviewable.');
const repeated=clone(source);repeated.departments[0].rooms.push(room('Same',[room('Same')]));
assert.equal(locate(repeated,'Service/Same/Same').parentPath,'Service/Same');
const tree={id:'$station',name:'Station',kind:'station',floorArea:10,children:[{id:'Service/Chapel',definitionPath:'Service/Chapel',name:'Chapel',kind:'template',selectedCount:3,children:[{id:'Service/Chapel#1',definitionPath:'Service/Chapel',name:'Chapel 1',kind:'instance',floorArea:10,children:[]}]}]};
assert.match(treeHtml({definition:source,tree},'Service/Chapel',new Set(['$station'])),/×1/,'Template count is direct instances rather than descendant rooms.');
console.log('Nested authoring passed: arbitrary-depth lookup, per-parent counts, rename/reference integrity, reparenting, subtree duplication/removal and direct-instance tree counts.');
