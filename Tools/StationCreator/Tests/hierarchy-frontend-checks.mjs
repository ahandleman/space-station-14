// Tests real authoring handlers and YAML API. Browser layout is not covered.
import assert from 'node:assert/strict';
import {createHierarchyEditor,renameProgramPath,removeProgramPath} from '../wwwroot/hierarchy-editor.js';
const base='http://127.0.0.1:8420';
let project=await(await fetch(base+'/api/default')).json(),records=0,invalidations=0;
const notices=[];
const editor=createHierarchyEditor({getProject:()=>project,record:()=>records++,changed:()=>invalidations++,redraw(){},notify:(...message)=>notices.push(message)});
const target=(dataset,value='',type='text')=>({dataset,value,type,checked:true,checkValidity:()=>true,closest(){return this;}});
const click=dataset=>editor.handleClick({target:target(dataset)});
const change=(key,value,type='text')=>editor.handleChange({target:target({programField:key},value,type)});
const select=programSelect=>click({programSelect});
editor.inspectorHtml();
assert.match(editor.inspectorHtml(),/Kitchen/);
select('Engineering/Atmos/TEG');assert.match(editor.detailsHtml(),/Required access origins/);
change('description','Shared generator area');
const engineering=project.config.departments.find(d=>d.id==='Engineering');
assert.equal(engineering.subdepartments[0].rooms[0].description,'Shared generator area');
select('Engineering');change('id','Power');
assert.ok(project.topology.nodes.includes('Power'));
assert.ok(project.topology.edges.every(e=>e.from!=='Engineering'&&e.to!=='Engineering'));
assert.equal(JSON.stringify(engineering.subdepartments[0].rooms[0].accessibleFrom),JSON.stringify(['Power','Power/Atmos']));
assert.equal(project.topology.nodePositions?.Engineering,undefined);
change('placementOrder',-1,'number');
change('topologyHub','','checkbox');
assert.equal(engineering.placementOrder,-1);
assert.equal(engineering.topologyHub,true);
assert.equal(project.config.departments.filter(d=>d.topologyHub).length,1);
select('Power/Atmos');change('id','Atmospherics');
assert.equal(JSON.stringify(engineering.subdepartments[0].rooms[0].accessibleFrom),JSON.stringify(['Power','Power/Atmospherics']));
click({programAction:'add-relation'});
assert.equal(project.config.hierarchyRelations.length,1);
editor.handleChange({target:target({programEdge:'weight'},'17.5','number')});
editor.handleChange({target:target({programEdge:'description'},'Prioritize internal atmosphere support')});
assert.equal(project.config.hierarchyRelations[0].weight,17.5);
assert.match(editor.detailsHtml(),/Prioritize internal/);
editor.handleChange({target:target({programEdge:'relation'},'delivery')});
editor.handleChange({target:target({programEdge:'purpose'},'items')});
const modes=target({programEdge:'allowedModes'});modes.selectedOptions=[{value:'staffPassage'},{value:'mail'}];editor.handleChange({target:modes});
assert.match(editor.detailsHtml(),/value="delivery" selected/);
assert.match(editor.detailsHtml(),/value="mail" selected/);
editor.handleChange({target:target({programEdge:'maxDistance'},'','number')});assert.equal(project.config.hierarchyRelations[0].maxDistance,null);
click({programAction:'remove-relation'});
assert.equal(project.config.hierarchyRelations.length,0);
select('Service');click({programAction:'add-subdepartment'});
const service=project.config.departments.find(d=>d.id==='Service'),sub=service.subdepartments.at(-1);
change('id','Chapel');change('description','Quiet public chapel');
click({programAction:'add-room'});change('id','Office');
assert.equal(sub.rooms[0].id,'Office');
click({programAction:'remove-item'});assert.equal(sub.rooms.length,0);
select('Service/Chapel');click({programAction:'remove-item'});assert.ok(!service.subdepartments.includes(sub));
click({programAction:'add-department'});
const added=project.config.departments.at(-1);assert.ok(project.topology.nodes.includes(added.id));assert.equal(typeof project.topology.nodes.at(-1),'string');
click({programAction:'remove-item'});assert.ok(!project.config.departments.includes(added));
assert.equal(records,invalidations);assert.equal(notices.length,0);

// The same helpers protect references when the original topology editor renames/deletes nodes.
project.config.hierarchyRelations=[{from:'Power/Atmospherics',to:'Service/Kitchen'}];
renameProgramPath(project,'Service','Civilian');assert.equal(project.config.hierarchyRelations[0].to,'Civilian/Kitchen');
removeProgramPath(project,'Civilian');assert.equal(project.config.hierarchyRelations.length,0);
// Restore a valid untouched document for the typed YAML endpoint round trip.
project=await(await fetch(base+'/api/default')).json();
project.config.spatial.deepMaintenanceMin=3;project.config.spatial.deepMaintenanceMax=5;
project.config.spatial.solarMin=1;project.config.spatial.solarMax=2;
const exported=await fetch(base+'/api/definition/export',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(project)});
assert.equal(exported.status,200);const yaml=await exported.text();assert.match(yaml,/subdepartments:/);assert.match(yaml,/accessibleFrom:/);assert.doesNotMatch(yaml,/spatialPlan:/);
const imported=await fetch(base+'/api/definition/import',{method:'POST',headers:{'Content-Type':'text/plain'},body:yaml});
assert.equal(imported.status,200,await imported.clone().text());const restored=await imported.json();
assert.equal(JSON.stringify(restored.config),JSON.stringify(project.config));assert.equal(JSON.stringify(restored.topology),JSON.stringify(project.topology));assert.equal(restored.spatialPlan,null);
const invalid=await fetch(base+'/api/definition/import',{method:'POST',headers:{'Content-Type':'text/plain'},body:'schemaVersion: 1\nconfig: {departments: null}'});assert.equal(invalid.status,400);
console.log('Program frontend passed: hierarchy CRUD, path renaming/removal, shared room origins, weighted relations, topology synchronization and typed YAML API round trip.');
