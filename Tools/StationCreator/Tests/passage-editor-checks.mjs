// Actual passage paint handlers: narrow continuous strokes and one undo record.
import assert from 'node:assert/strict';
import {createSpatialEditor} from '../wwwroot/spatial-editor.js';
let records=0,boundaries=0;
const plan={cellSize:5,envelope:[],seeds:[],regions:[],ports:[],publicReservations:[],serviceReservations:[],initialServiceReservations:[],publicCorridors:[],maintenance:[],walls:[],hull:[],reservedExterior:[],structuralReserve:[],deepMaintenanceRooms:[]};
for(let y=0;y<32;y++)for(let x=0;x<32;x++)plan.envelope.push({x,y});
const project={config:{width:32,height:32,maintenanceWidth:2,departments:[],spatial:{cellSize:5,maintenancePassageMaxWidth:3}},spatialPlan:plan};
const editor=createSpatialEditor({getProject:()=>project,record:()=>records++,changed(){},redraw(){},drawMap(){},notify(){},run:async key=>{assert.equal(key,'boundaries');boundaries++;}});
const tool={dataset:{spatialTool:'maintenance'},closest(){return this;}};
editor.handleClick({target:tool});
editor.pointerDown({target:{closest:()=>null}},{x:4.1,y:4.1},3);
editor.pointerMove({x:19.1,y:4.1},3);
await editor.pointerUp(3);
const keys=new Set(plan.maintenance.map(p=>`${p.x},${p.y}`));
assert.equal(keys.size,34);
for(let x=4;x<=20;x++)for(let y=4;y<=5;y++)assert.ok(keys.has(`${x},${y}`),'A fast stroke must retain continuous two-tile floor.');
assert.equal(records,1);assert.equal(boundaries,1);
assert.match(editor.inspectorHtml(3),/Maximum open width/);
assert.match(editor.inspectorHtml(3),/Hall-connected maintenance rooms/);
assert.match(editor.help(3),/2-tile passage brush/);
editor.handleChange({target:{dataset:{spatialSetting:'maintenancePocketPreference'},value:'rooms',type:'select-one',checkValidity:()=>true}},3);
assert.equal(project.config.spatial.maintenancePocketPreference,'rooms');
assert.match(editor.inspectorHtml(3),/value="rooms" selected/);
plan.deepMaintenanceRooms=[{cells:[{x:23,y:4}],walls:[],portCells:[]}];
editor.pointerDown({target:{closest:()=>null}},{x:23,y:4},3);await editor.pointerUp(3);
assert.ok(!plan.maintenance.some(p=>p.x===23&&p.y===4),'The brush cannot overwrite a room footprint.');
plan.initialServiceReservations=[{x:1,y:1}];plan.serviceReservations=[{x:9,y:9}];
const layers=[];editor.graphHtml((cells,color,name)=>{layers.push({name,cells});return '';},1);
assert.equal(JSON.stringify(layers.find(l=>l.name==='service-reservation').cells),JSON.stringify(plan.initialServiceReservations));
console.log('Passage editor passed: tile-width continuous painting, feature protection, one-stroke history, width controls and upstream reservation display.');
